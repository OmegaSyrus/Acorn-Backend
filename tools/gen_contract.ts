// Writes supabase/functions/_shared/contract.ts from contract/: the schemas
// and the skill ids, so the deployed function carries them (it can't read
// files outside supabase/functions). CI fails if the file is out of date.
//   deno run -A tools/gen_contract.ts         (write)
//   deno run -A tools/gen_contract.ts --check (compare only)
const root = new URL("../", import.meta.url);
const read = (p: string) => JSON.parse(Deno.readTextFileSync(new URL(p, root)));
const schemas: Record<string, unknown> = {
  event_v2: read("contract/schemas/event.v2.schema.json"),
  snapshot_v1: read("contract/schemas/snapshot.v1.schema.json"),
  settings_v1: read("contract/schemas/settings.v1.schema.json"),
  manifest_v1: read("contract/schemas/manifest.v1.schema.json"),
};
const skillRows = read("contract/skills.json").skills as { id: string; label: string }[];
const skills = skillRows.map((s) => s.id);
const labels = Object.fromEntries(skillRows.map((s) => [s.id, s.label]));
const text = `// Generated by tools/gen_contract.ts from contract/. Do not edit.\n` +
  `export const SCHEMAS = ${JSON.stringify(schemas, null, 1)} as const;\n` +
  `export const SKILLS: string[] = ${JSON.stringify(skills)};\n` +
  `export const SKILL_LABELS: Record<string, string> = ${JSON.stringify(labels, null, 1)};\n`;
const out = new URL("supabase/functions/_shared/contract.ts", root);
if (Deno.args.includes("--check")) {
  const now = Deno.readTextFileSync(out);
  if (now !== text) {
    console.error("supabase/functions/_shared/contract.ts is out of date: run deno run -A tools/gen_contract.ts");
    Deno.exit(1);
  }
  console.log("contract.ts up to date");
} else {
  Deno.writeTextFileSync(out, text);
  console.log("wrote supabase/functions/_shared/contract.ts");
}
